const LANGUAGE_STORAGE_KEY = 'cocopi-language';
const I18nContext = createContext(null);

export function normalizeLanguage(value) {
  const normalized = String(value || '').trim().toLowerCase();
  if (normalized === 'en' || normalized.startsWith('en-')) return 'en';
  if (normalized === 'zh-hant' || normalized.includes('hant') || normalized === 'zh-hk') {
    return 'zh-hant';
  }
  return 'zh-hans';
}

function getInitialLanguage() {
  if (typeof window === 'undefined') return 'zh-hans';
  const queryLanguage = new URLSearchParams(window.location.search).get('lang');
  if (queryLanguage) return normalizeLanguage(queryLanguage);
  try {
    return normalizeLanguage(localStorage.getItem(LANGUAGE_STORAGE_KEY));
  } catch (_) {
    return 'zh-hans';
  }
}

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(getInitialLanguage);

  useEffect(() => {
    try {
      localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
    } catch (_) {
      // Language still works for the current session if storage is unavailable.
    }
    document.documentElement.lang =
      language === 'en' ? 'en' : language === 'zh-hant' ? 'zh-Hant-HK' : 'zh-Hans';
    const url = new URL(window.location.href);
    url.searchParams.set('lang', language);
    window.history.replaceState(null, '', url);
  }, [language]);

  const value = useMemo(
    () => ({
      language,
      setLanguage: (nextLanguage) => setLanguage(normalizeLanguage(nextLanguage)),
      t(key, variables = {}) {
        const template =
          MESSAGES[language]?.[key] ?? MESSAGES['zh-hans'][key] ?? key;
        return template.replace(/\{(\w+)\}/g, (_, name) =>
          String(variables[name] ?? `{${name}}`)
        );
      }
    }),
    [language]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) {
    throw new Error('useI18n must be used inside LanguageProvider');
  }
  return value;
}
